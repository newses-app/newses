import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterAll, describe, expect, it } from 'vitest';
import { silentLogger } from '../test/fakes.ts';
import {
  INSTALLED_MODULE,
  installedModule,
  installedSpecs,
  installPlugins,
  isPluginSpec,
  linkInstalled,
  parsePluginSpecs,
} from './install.ts';
import { PluginRegistry } from './registry.ts';

// Under server/, as deployments install them, so plugins resolve the server's zod and contract.
const PLUGINS_ROOT = fileURLToPath(new URL('../../.plugins/', import.meta.url));
const scratch = mkdtempSync(join(tmpdir(), 'plugin-fixtures-'));
const installDirs: string[] = [];

afterAll(() => {
  rmSync(scratch, { recursive: true, force: true });
  for (const dir of installDirs) rmSync(dir, { recursive: true, force: true });
});

/** A package folder with `files`, for `file:` installs. */
function fixturePackage(name: string, manifest: object, files: Record<string, string> = {}) {
  const dir = join(scratch, name.replace('/', '__'));
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ name, ...manifest }));
  for (const [file, text] of Object.entries(files)) writeFileSync(join(dir, file), text);
  return `file:${dir}`;
}

const installDir = (name: string) => {
  const dir = join(PLUGINS_ROOT, `test-${name}-${String(process.pid)}`);
  installDirs.push(dir);
  return dir;
};

describe('plugin specs', () => {
  it('take npm packages at exact versions only, each once', () => {
    for (const spec of ['webhook@1.0.0', '@newses/plugin-webhook@0.1.0', 'a.b-c@1.2.3-rc.1'])
      expect(isPluginSpec(spec), spec).toBe(true);
    for (const spec of [
      'webhook',
      'webhook@^1.0.0',
      'webhook@latest',
      'webhook@1.0',
      'Webhook@1.0.0',
      'github:owner/webhook',
      'webhook@file:../webhook',
      '@scope@1.0.0',
    ])
      expect(isPluginSpec(spec), spec).toBe(false);
    expect(parsePluginSpecs(['@a/b@1.0.0', 'c@2.0.0'])).toEqual([
      { name: '@a/b', version: '1.0.0' },
      { name: 'c', version: '2.0.0' },
    ]);
    expect(() => parsePluginSpecs(['c@1.0.0', 'c@2.0.0'])).toThrow('c is listed more than once');
    expect(() => parsePluginSpecs(['c@^1'])).toThrow('not a package at an exact version');
    expect(() =>
      parsePluginSpecs(Array.from({ length: 21 }, (_, i) => `p${String(i)}@1.0.0`)),
    ).toThrow('At most 20 plugins');
  });

  it('list the installed plugins in a module of default imports', () => {
    expect(installedModule(['@a/b@1.0.0', 'c@2.0.0'])).toBe(
      [
        '// Generated by server/src/plugins/install.ts: the plugins this deployment installs.',
        'import plugin0 from "@a/b";',
        'import plugin1 from "c";',
        '',
        'export const INSTALLED_PLUGINS = [',
        '  { source: "@a/b@1.0.0", plugin: plugin0 },',
        '  { source: "c@2.0.0", plugin: plugin1 },',
        '];',
        '',
      ].join('\n'),
    );
  });
});

describe('installPlugins', () => {
  it('installs the plugins without scripts, sharing the server’s zod and contract', async () => {
    const source = fixturePackage(
      'newses-plugin-fixture',
      {
        version: '1.0.0',
        type: 'module',
        main: 'index.js',
        peerDependencies: { zod: '^4.0.0', '@newses/plugin-api': '^0.1.0' },
        scripts: { postinstall: 'node -e "process.exit(1)"' },
      },
      {
        'index.js': `import { definePlugin, secret } from '@newses/plugin-api';
import { z } from 'zod';
export default definePlugin({
  id: 'fixture',
  version: '1.0.0',
  apiVersion: '^0.1',
  scopes: ['instance'],
  settings: { instance: z.object({ key: secret(), region: z.string().default('eu') }) },
  hooks: {},
});
`,
      },
    );
    const dir = installDir('fixture');
    installPlugins({
      dir,
      specs: ['newses-plugin-fixture@1.0.0'],
      audit: false,
      sources: { 'newses-plugin-fixture': source },
    });
    expect(installedSpecs(dir)).toEqual(['newses-plugin-fixture@1.0.0']);
    const { INSTALLED_PLUGINS } = (await import(join(dir, INSTALLED_MODULE))) as {
      INSTALLED_PLUGINS: { source: string; plugin: unknown }[];
    };
    const registry = PluginRegistry.load(INSTALLED_PLUGINS, { logger: silentLogger });
    expect(registry.refused).toEqual([]);
    const plugin = registry.get('fixture');
    expect(plugin?.source).toBe('newses-plugin-fixture@1.0.0');
    // The secret mark survives only when the plugin's zod is the server's.
    expect(plugin?.settings.instance?.fields.get('key')).toEqual({
      secret: true,
      url: false,
      multiline: false,
    });
  });

  it('refuses a plugin that brings its own zod', () => {
    const zod = fixturePackage('zod', { version: '4.0.0' });
    const source = fixturePackage('newses-plugin-own-zod', {
      version: '1.0.0',
      dependencies: { zod },
    });
    expect(() => {
      installPlugins({
        dir: installDir('own-zod'),
        specs: ['newses-plugin-own-zod@1.0.0'],
        audit: false,
        sources: { 'newses-plugin-own-zod': source },
      });
    }).toThrow('newses-plugin-own-zod brings its own zod');
  });

  it('audits what it installed, and lists no plugins without installing any', () => {
    const calls: string[][] = [];
    const dir = installDir('audit');
    installPlugins({
      dir,
      specs: ['webhook@1.0.0'],
      audit: true,
      npm: (args) => calls.push(args),
    });
    expect(calls.map((args) => args[0])).toEqual(['install', 'audit']);
    expect(calls[0]).toEqual(expect.arrayContaining(['--ignore-scripts', '--legacy-peer-deps']));
    expect(calls[1]).toEqual(['audit', '--omit=dev', '--audit-level=high']);
    expect(JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))).toMatchObject({
      dependencies: { webhook: '1.0.0' },
    });

    calls.length = 0;
    installPlugins({ dir, specs: [], audit: true, npm: (args) => calls.push(args) });
    expect(calls).toEqual([]);
    expect(installedSpecs(dir)).toEqual([]);
    expect(installedSpecs(join(dir, 'missing'))).toBeNull();
  });

  it('links the list for a process run from source', () => {
    const target = join(scratch, 'src', 'installed.ts');
    mkdirSync(join(scratch, 'src'));
    linkInstalled(join(scratch, 'plugins'), target);
    expect(readFileSync(target, 'utf8')).toContain(
      `export { INSTALLED_PLUGINS } from "../plugins/${INSTALLED_MODULE}";`,
    );
  });
});
